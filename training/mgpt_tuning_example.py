import torch
import numpy as np
from tqdm import tqdm
from torch.utils.data import Dataset, DataLoader
from transformers import GPT2LMHeadModel, GPT2Tokenizer
import os

class TextDataset(Dataset):
    def __init__(self, path, tokenizer, seq_length=512):
        with open(path, encoding='utf-8') as f:  # Ensure proper encoding is set for file reading
            data = f.read()
        tokens = tokenizer.encode(data)
        examples = []
        for i in range(0, len(tokens) - seq_length + 1, seq_length):
            examples.append(tokens[i:i + seq_length])
        self.samples = torch.tensor(examples, dtype=torch.long)  # Use torch.tensor with dtype specified
        print('Loaded samples:', len(self.samples))

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, item):
        return self.samples[item]


model_name = "sberbank-ai/mGPT"

tokenizer = GPT2Tokenizer.from_pretrained(model_name)
model = GPT2LMHeadModel.from_pretrained(model_name, gradient_checkpointing=True, use_cache=False)

# Downloading the file should be done outside of the script or checked if it exists to avoid redundancy
text_file = 'text.txt'
if not os.path.isfile(text_file):
    os.system('wget https://raw.githubusercontent.com/ipetrushin/WarAndPeaceTask/master/voyna-i-mir-tom-1-unicode.txt -O ' + text_file)

dataset = TextDataset(text_file, tokenizer)
dataloader = DataLoader(dataset, batch_size=1, shuffle=True, drop_last=True)

# Freeze transformer layers except the first and the last one. Do not freeze any layernorms
for n, p in model.named_parameters():
    if 'transformer.h' in n:
        layer_num = int(n.split('.')[2])
        if 'ln_' not in n and layer_num > 0 and layer_num < 23:
            p.requires_grad = False
            print('Freeze', n)

model.to(torch.device("cuda" if torch.cuda.is_available() else "cpu"))
optimizer = torch.optim.SGD(params=model.parameters(), lr=1e-5)

model.train()
for epoch in range(3):
    print('Epoch', epoch)
    progressbar = tqdm(dataloader)
    losses = []
    for batch in progressbar:
        optimizer.zero_grad()

        batch = batch.to(model.device)
        outputs = model(batch, labels=batch)
        loss = outputs.loss

        loss.backward()
        optimizer.step()

        losses.append(loss.detach().item())
        progressbar.set_description("Loss: %.3f" % np.mean(losses[-10:]))

# prompt: Save trained model to output folder

output_dir = './output'
if not os.path.exists(output_dir):
    os.makedirs(output_dir)
model.save_pretrained(output_dir)
tokenizer.save_pretrained(output_dir)

# prompt: Open pretrained model from output folder and use example

model = GPT2LMHeadModel.from_pretrained(output_dir, use_cache=False)
model.config.gradient_checkpointing = True
model.to(torch.device("cuda" if torch.cuda.is_available() else "cpu"))
tokenizer = GPT2Tokenizer.from_pretrained(output_dir)
input_ids = torch.tensor(tokenizer.encode(
    "Пушкин ", return_tensors="pt"
), dtype=torch.long).to(model.device)
with torch.no_grad():
    output = model(input_ids, labels=input_ids)
    loss = output.loss
    logits = output.logits
    generated_ids = model.generate(input_ids, max_length=100, num_return_sequences=1)
